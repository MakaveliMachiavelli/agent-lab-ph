def run_composio(args):
    env = dict(os.environ)
    env["PATH"] = os.path.expanduser("~/.composio/bin") + ":" + env["PATH"]
    result = subprocess.run(
        [COMPOSIO] + args, capture_output=True, text=True, timeout=120, env=env
    )
    return result.stdout + result.stderr

fb_args = ["execute", "FACEBOOK_CREATE_POST", "-d", json.dumps({
    "page_id": FB_PAGE_ID,
    "message": explanation,
    "published": True
})]

result = run_composio(fb_args)
print(result)

# Save to file
with open("/home/allenos/agent-lab-ph/TRANSPARENCY_POST_AI.md", "w") as f:
    f.write(explanation)
print("\nSaved to TRANSPARENCY_POST_AI.md")